#!/usr/bin/env python3
"""Freeze a bounded workload-trained GCC PGO service comparison."""

from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path
from typing import Any

try:
    from experiments.e5b_ingest import load_object, sha256_file
except ModuleNotFoundError as error:
    if error.name != "experiments":
        raise
    from e5b_ingest import load_object, sha256_file


INPUT_PATHS = {
    "base_contract": Path("experiments/e7a_contract.json"),
    "e7c_manifest": Path("results/manifests/e7c-30696606993.json"),
    "e9a_manifest": Path("results/manifests/e9a-30764802071.json"),
    "manifest": Path("results/manifests/e3f-30656151957.json"),
    "models": Path("experiments/e3f_models.json"),
    "tasks": Path("experiments/e3_tasks.json"),
    "probe": Path("experiments/e5b_inference_probe.py"),
    "runtime_closure": Path("experiments/e7a_runtime_closure.py"),
    "profile_inventory": Path("experiments/e18a_profile_inventory.py"),
    "cell": Path("experiments/e18a_cell.sh"),
    "freeze": Path("experiments/e18a_freeze.py"),
    "ingest": Path("experiments/e18a_ingest.py"),
    "test": Path("tests/test_e18a.py"),
    "patch_features": Path(
        "patches/llama.cpp/b10216/0001-kleidiai-use-validated-arm-features.patch"
    ),
    "patch_q8": Path("patches/llama.cpp/0002-arm-q8-vector-narrowing-stores.patch"),
    "patch_reasoning": Path(
        "patches/llama.cpp/0003-reasoning-budget-forced-token-guard.patch"
    ),
}


def build_contract(root: Path) -> dict[str, Any]:
    base = load_object(root / INPUT_PATHS["base_contract"])
    e7c = load_object(root / INPUT_PATHS["e7c_manifest"])
    e9a = load_object(root / INPUT_PATHS["e9a_manifest"])
    models = load_object(root / INPUT_PATHS["models"])
    if (
        base.get("experiment_id") != "E7a"
        or e7c.get("status") != "valid_http_dependency_pruned_launch_integration"
        or e9a.get("status") != "valid_final_service_win"
        or e7c.get("validation", {}).get("openssl_dependencies_absent") is not True
    ):
        raise ValueError("E18a prerequisite differs")
    candidate = base["selected"]["candidate"]
    variant = models["variants"][candidate]
    model_file = variant["files"][0]
    if (
        model_file["sha256"] != base["selected"]["model_sha256"]
        or model_file["size_bytes"] != base["selected"]["model_size_bytes"]
    ):
        raise ValueError("E18a selected model differs")

    inputs: dict[str, str] = {}
    for name, relative in INPUT_PATHS.items():
        inputs[f"{name}_path"] = relative.as_posix()
        inputs[f"{name}_sha256"] = sha256_file(root / relative)
    runtime = copy.deepcopy(base["runtime"])
    order = []
    for block in range(3):
        first = block * 2 + 1
        second = first + 1
        order.extend(
            [
                {"profile": "release_control", "repetition": first},
                {"profile": "workload_pgo", "repetition": first},
                {"profile": "workload_pgo", "repetition": second},
                {"profile": "release_control", "repetition": second},
            ]
        )
    profile_root = "/tmp/Pareto64-E18a-profile"
    generate_flags = f"-fprofile-generate={profile_root}"
    use_flags = (
        f"-fprofile-use={profile_root} -fprofile-correction "
        "-fprofile-partial-training"
    )
    return {
        "schema_version": 1,
        "experiment_id": "E18a",
        "title": "Workload-trained GCC PGO service comparison",
        "state": (
            "frozen before any instrumented training build, profile data, PGO-use "
            "binary, service result, or build/runtime outcome was observed"
        ),
        "hypothesis": (
            "A GCC profile generated by one exact 30-task pass through the final "
            "OpenSSL-off service improves repeated median native throughput by at "
            "least 2% while reducing median latency and CPU seconds/request by at "
            "least 1%, without quality, p95, readiness, memory, or closure regression."
        ),
        "inputs": inputs,
        "prerequisites": {
            "e7c_summary_sha256": sha256_file(root / INPUT_PATHS["e7c_manifest"]),
            "e9a_summary_sha256": sha256_file(root / INPUT_PATHS["e9a_manifest"]),
            "exact_final_service": True,
        },
        "runtime": runtime,
        "selected": {
            **base["selected"],
            "repository": variant["repository"],
            "revision": variant["revision"],
            "path": variant["entrypoint"],
        },
        "service": base["service"],
        "request": base["request"],
        "training": {
            "build_directory": "/tmp/llama.cpp-E18a-pgo-build",
            "profile_data_directory": profile_root,
            "profile_generate_flags": generate_flags,
            "profile_use_flags": use_flags,
            "same_build_directory_for_generate_and_use": True,
            "workload": "one exact E3f 30-task selected-model service pass after two frozen warmups",
            "quality_must_match_selected_predictions": True,
            "minimum_gcda_files": 20,
            "training_result_is_not_performance_evidence": True,
        },
        "build": {
            "common_cmake_arguments": [
                "-DCMAKE_BUILD_TYPE=Release",
                "-DGGML_CPU_KLEIDIAI=ON",
                "-DGGML_LTO=OFF",
                "-DGGML_NATIVE=ON",
                "-DLLAMA_BUILD_EXAMPLES=OFF",
                "-DLLAMA_BUILD_SERVER=ON",
                "-DLLAMA_BUILD_TESTS=OFF",
                "-DLLAMA_CURL=OFF",
                "-DLLAMA_OPENSSL=OFF",
            ],
            "common_cmake_cache_entries": [
                "CMAKE_BUILD_TYPE:STRING=Release",
                "CMAKE_GENERATOR:INTERNAL=Ninja",
                "GGML_CPU_KLEIDIAI:BOOL=ON",
                "GGML_LTO:BOOL=OFF",
                "GGML_NATIVE:BOOL=ON",
                "LLAMA_BUILD_EXAMPLES:BOOL=OFF",
                "LLAMA_BUILD_SERVER:BOOL=ON",
                "LLAMA_BUILD_TESTS:BOOL=OFF",
                "LLAMA_CURL:UNINITIALIZED=OFF",
                "LLAMA_OPENSSL:BOOL=OFF",
            ],
            "profiles": {
                "release_control": {
                    "pgo": False,
                    "required_command_patterns": [],
                    "forbidden_command_patterns": ["-fprofile-generate", "-fprofile-use"],
                },
                "workload_pgo": {
                    "pgo": True,
                    "required_command_patterns": [
                        f"-fprofile-use={profile_root}",
                        "-fprofile-correction",
                        "-fprofile-partial-training",
                    ],
                    "forbidden_command_patterns": ["-fprofile-generate"],
                },
            },
            "runtime_closure": (
                "Hash the server and every build-local transitive shared library "
                "for both measured binaries."
            ),
        },
        "execution": {
            "runner": "ubuntu-24.04-arm",
            "baseline_profile": "release_control",
            "candidate_profile": "workload_pgo",
            "repetitions_per_profile": 6,
            "fresh_server_per_cell": True,
            "order": order,
            "reverse_balanced_blocks": 3,
        },
        "acceptance": {
            **base["acceptance"],
            "minimum_throughput_ratio": 1.02,
            "maximum_median_http_latency_ratio": 0.99,
            "maximum_p95_http_latency_ratio": 1.02,
            "maximum_cpu_seconds_per_request_ratio": 0.99,
            "maximum_ready_time_ratio": 1.10,
            "maximum_candidate_rss_ratio": 1.02,
            "maximum_runtime_closure_ratio": 1.05,
            "maximum_candidate_throughput_cv": 0.02,
        },
        "decision": {
            "candidate_must_pass_every_gate": True,
            "quality_evaluated_before_performance_promotion": True,
            "profile_training_is_workload_specific": True,
            "no_generic_default_or_other_model_claim": True,
            "no_combination_with_LTO_without_separate_experiment": True,
        },
        "negative_result_rule": (
            "Retain missing or unusable profile data, compiler warnings, build failure, "
            "quality drift, speed or CPU regression, p95/readiness/RSS/closure regression, "
            "and scheduler noise without changing the training pass, flags, repetitions, "
            "order, service, workload, or thresholds."
        ),
        "claim_boundary": (
            "E18a can establish only a workload-trained GCC PGO effect for the exact "
            "patched b10216 OpenSSL-off Q4_K_M service and 30-task prompt-heavy workload "
            "on one four-vCPU Neoverse-N2 GitHub Arm runner. It makes no generic PGO, "
            "other-model, long-context, fleet, energy, PMU, device, or cost claim."
        ),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    contract = build_contract(args.root)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(contract, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"sha256": sha256_file(args.output)}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
